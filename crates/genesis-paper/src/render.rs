//! Turning a draft and its grounding data into `paper.tex` and `paper.md`.
//!
//! Tables and figures are generated here, from the grounding data, and
//! placed where the draft asks for them; a float the draft never placed is
//! appended, so evidence cannot be left out by omission. The model's prose
//! is escaped on the way into LaTeX.

use crate::data::PaperData;
use crate::draft::{Draft, SECTIONS};
use crate::references::Reference;
use crate::text::{escape_inline, escape_latex, parse_prose, Block, FloatKind, Inline};
use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;

/// The statement every rendering carries.
pub const GENERATED_BY: &str =
    "Generated by Genesis from the recorded evidence of one automated run.";

/// A number as tables show it: integers whole, otherwise four decimals, or
/// three significant digits in scientific notation when that would show
/// nothing.
pub fn format_number(value: f64) -> String {
    if !value.is_finite() {
        return "n/a".to_string();
    }
    if value == value.trunc() && value.abs() < 1e12 {
        return format!("{}", value as i64);
    }
    if value.abs() >= 0.001 {
        format!("{value:.4}")
    } else {
        format!("{value:.2e}")
    }
}

/// A measured value as table cells show it: always four decimals, so a
/// column lines up, or scientific notation when that would show nothing.
pub fn format_metric(value: f64) -> String {
    if !value.is_finite() {
        "n/a".to_string()
    } else if value != 0.0 && value.abs() < 0.001 {
        format!("{value:.2e}")
    } else {
        format!("{value:.4}")
    }
}

fn format_p(value: Option<f64>) -> String {
    match value.filter(|p| p.is_finite()) {
        Some(p) if p < 0.001 => "<0.001".to_string(),
        Some(p) => format!("{p:.3}"),
        None => "n/a".to_string(),
    }
}

fn format_interval(low: f64, high: f64) -> String {
    format!("[{}, {}]", format_metric(low), format_metric(high))
}

/// A generated table or figure.
#[derive(Debug, Clone, PartialEq)]
pub struct Float {
    pub kind: FloatKind,
    pub name: &'static str,
    /// What it shows, for the writer's prompt.
    pub description: &'static str,
    pub latex: String,
    /// Markdown body; `{N}` stands for the float's number.
    pub markdown: String,
    /// File name and content of the figure beside the markdown.
    pub svg: Option<(String, String)>,
    /// The section an unplaced float is appended to.
    pub home: &'static str,
}

fn latex_table(
    name: &str,
    caption: &str,
    columns: &str,
    header: &[&str],
    rows: &[Vec<String>],
) -> String {
    let mut out = format!(
        "\\begin{{table}}\n\\centering\n\\caption{{{}}}\n\\label{{tab:{name}}}\n\\begin{{tabular}}{{{columns}}}\n\\toprule\n{} \\\\\n\\midrule\n",
        escape_inline(caption),
        header.iter().map(|cell| escape_inline(cell)).collect::<Vec<_>>().join(" & ")
    );
    for row in rows {
        let cells: Vec<String> = row.iter().map(|cell| escape_inline(cell)).collect();
        let _ = writeln!(out, "{} \\\\", cells.join(" & "));
    }
    out.push_str("\\bottomrule\n\\end{tabular}\n\\end{table}\n");
    out
}

fn markdown_table(caption: &str, header: &[&str], rows: &[Vec<String>]) -> String {
    let cell = |text: &str| {
        text.replace('|', "\\|")
            .split_whitespace()
            .collect::<Vec<_>>()
            .join(" ")
    };
    let mut out = format!(
        "**Table {{N}}.** {caption}\n\n| {} |\n|{}\n",
        header.join(" | "),
        " --- |".repeat(header.len())
    );
    for row in rows {
        let _ = writeln!(
            out,
            "| {} |",
            row.iter()
                .map(|text| cell(text))
                .collect::<Vec<_>>()
                .join(" | ")
        );
    }
    out
}

fn table(
    name: &'static str,
    description: &'static str,
    home: &'static str,
    caption: &str,
    columns: &str,
    header: &[&str],
    rows: Vec<Vec<String>>,
) -> Float {
    Float {
        kind: FloatKind::Table,
        name,
        description,
        latex: latex_table(name, caption, columns, header, &rows),
        markdown: markdown_table(caption, header, &rows),
        svg: None,
        home,
    }
}

fn xml(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

const SVG_WIDTH: f64 = 640.0;
const SVG_HEIGHT: f64 = 360.0;
const SVG_LEFT: f64 = 70.0;
const SVG_RIGHT: f64 = 20.0;
const SVG_TOP: f64 = 20.0;
const SVG_BOTTOM: f64 = 60.0;

/// Shared frame of both charts: axes, the y range and the two axis titles.
/// Colours follow the page's text colour, so the figure reads on light and
/// dark backgrounds.
fn svg_frame(y_min: f64, y_max: f64, x_title: &str, y_title: &str, body: &str) -> String {
    format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 {SVG_WIDTH} {SVG_HEIGHT}\" font-family=\"sans-serif\" font-size=\"12\">\n\
         <g fill=\"none\" stroke=\"currentColor\" stroke-width=\"1\">\n\
         <line x1=\"{SVG_LEFT}\" y1=\"{SVG_TOP}\" x2=\"{SVG_LEFT}\" y2=\"{bottom}\"/>\n\
         <line x1=\"{SVG_LEFT}\" y1=\"{bottom}\" x2=\"{right}\" y2=\"{bottom}\"/>\n</g>\n\
         <g fill=\"currentColor\">\n\
         <text x=\"{label_x}\" y=\"{top_label}\" text-anchor=\"end\">{}</text>\n\
         <text x=\"{label_x}\" y=\"{bottom}\" text-anchor=\"end\">{}</text>\n\
         <text x=\"{mid_x}\" y=\"{title_y}\" text-anchor=\"middle\">{}</text>\n\
         <text x=\"14\" y=\"{mid_y}\" text-anchor=\"middle\" transform=\"rotate(-90 14 {mid_y})\">{}</text>\n</g>\n{body}</svg>\n",
        format_metric(y_max),
        format_metric(y_min),
        xml(x_title),
        xml(y_title),
        bottom = SVG_HEIGHT - SVG_BOTTOM,
        right = SVG_WIDTH - SVG_RIGHT,
        label_x = SVG_LEFT - 6.0,
        top_label = SVG_TOP + 4.0,
        mid_x = (SVG_LEFT + SVG_WIDTH - SVG_RIGHT) / 2.0,
        title_y = SVG_HEIGHT - 8.0,
        mid_y = (SVG_TOP + SVG_HEIGHT - SVG_BOTTOM) / 2.0,
    )
}

fn scale(value: f64, low: f64, high: f64, from: f64, to: f64) -> f64 {
    if high <= low {
        (from + to) / 2.0
    } else {
        from + (value - low) / (high - low) * (to - from)
    }
}

fn padded_range(values: impl Iterator<Item = f64>) -> (f64, f64) {
    let (mut low, mut high) = (f64::INFINITY, f64::NEG_INFINITY);
    for value in values.filter(|value| value.is_finite()) {
        low = low.min(value);
        high = high.max(value);
    }
    if !low.is_finite() {
        return (0.0, 1.0);
    }
    let pad = if high > low {
        0.05 * (high - low)
    } else {
        0.5 * high.abs().max(1.0)
    };
    (low - pad, high + pad)
}

/// One row per label: a line from `low` to `high` with a dot at the mean,
/// labels on the left where they stay horizontal and readable.
fn interval_svg(rows: &[(String, f64, f64, f64)], x_title: &str) -> String {
    const LEFT: f64 = 190.0;
    const ROW: f64 = 34.0;
    let height = SVG_TOP + rows.len() as f64 * ROW + SVG_BOTTOM;
    let axis_y = height - SVG_BOTTOM;
    let (x_min, x_max) = padded_range(
        rows.iter()
            .flat_map(|(_, mean, low, high)| [*mean, *low, *high]),
    );
    let place = |value: f64| scale(value, x_min, x_max, LEFT, SVG_WIDTH - SVG_RIGHT);
    let mut out = format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 {SVG_WIDTH} {height}\" font-family=\"sans-serif\" font-size=\"12\">\n\
         <line x1=\"{LEFT}\" y1=\"{axis_y}\" x2=\"{right}\" y2=\"{axis_y}\" stroke=\"currentColor\"/>\n\
         <g fill=\"currentColor\">\n<text x=\"{LEFT}\" y=\"{tick}\" text-anchor=\"middle\">{}</text>\n\
         <text x=\"{right}\" y=\"{tick}\" text-anchor=\"middle\">{}</text>\n\
         <text x=\"{mid}\" y=\"{title}\" text-anchor=\"middle\">{}</text>\n",
        format_metric(x_min),
        format_metric(x_max),
        xml(x_title),
        right = SVG_WIDTH - SVG_RIGHT,
        tick = axis_y + 16.0,
        mid = (LEFT + SVG_WIDTH - SVG_RIGHT) / 2.0,
        title = height - 8.0,
    );
    for (index, (label, _, _, _)) in rows.iter().enumerate() {
        let y = SVG_TOP + (index as f64 + 0.5) * ROW;
        let _ = writeln!(
            out,
            "<text x=\"{:.1}\" y=\"{:.1}\" text-anchor=\"end\">{}</text>",
            LEFT - 12.0,
            y + 4.0,
            xml(label)
        );
    }
    out.push_str("</g>\n<g stroke=\"#3b82f6\" stroke-width=\"2\" fill=\"#3b82f6\">\n");
    for (index, (_, mean, low, high)) in rows.iter().enumerate() {
        let y = SVG_TOP + (index as f64 + 0.5) * ROW;
        let _ = writeln!(
            out,
            "<line x1=\"{:.1}\" y1=\"{y:.1}\" x2=\"{:.1}\" y2=\"{y:.1}\"/>\n<circle cx=\"{:.1}\" cy=\"{y:.1}\" r=\"4\" stroke=\"none\"/>",
            place(*low),
            place(*high),
            place(*mean)
        );
    }
    out.push_str("</g>\n</svg>\n");
    out
}

fn improvement_figure(data: &PaperData) -> Option<Float> {
    let trace = &data.improvement_trace;
    if trace.is_empty() {
        return None;
    }
    let last_generation = data
        .top_programs
        .iter()
        .map(|row| row.generation)
        .max()
        .unwrap_or(0)
        .max(trace[trace.len() - 1].generation);
    let caption = "Best combined score among correct programs after each generation of the search (search-time scores).";
    let coordinates: Vec<String> = trace
        .iter()
        .map(|step| format!("({},{})", step.generation, step.combined_score))
        .collect();
    let last = last_generation.max(1);
    let tick_step = last.div_ceil(8).max(1);
    let ticks: Vec<String> = (0..=last)
        .step_by(tick_step as usize)
        .map(|tick| tick.to_string())
        .collect();
    let latex = format!(
        "\\begin{{figure}}\n\\centering\n\\begin{{tikzpicture}}\n\\begin{{axis}}[width=0.85\\linewidth, height=5.2cm, xlabel={{Generation}}, ylabel={{Best combined score}}, \
         xmin=0, xmax={last}, xtick={{{}}}, const plot]\n\\addplot[blue, thick, mark=*, mark size=1.5pt] coordinates {{{} ({last},{})}};\n\\end{{axis}}\n\\end{{tikzpicture}}\n\
         \\caption{{{}}}\n\\label{{fig:improvement}}\n\\end{{figure}}\n",
        ticks.join(","),
        coordinates.join(" "),
        trace[trace.len() - 1].combined_score,
        escape_inline(caption)
    );

    let (y_min, y_max) = padded_range(trace.iter().map(|step| step.combined_score));
    let x_max = f64::from(last_generation.max(1));
    let place = |generation: f64, score: f64| {
        (
            scale(generation, 0.0, x_max, SVG_LEFT, SVG_WIDTH - SVG_RIGHT),
            scale(score, y_min, y_max, SVG_HEIGHT - SVG_BOTTOM, SVG_TOP),
        )
    };
    let mut path = String::new();
    let mut marks = String::new();
    let mut previous: Option<f64> = None;
    for step in trace {
        let (x, y) = place(f64::from(step.generation), step.combined_score);
        match previous {
            None => {
                let _ = write!(path, "M{x:.1},{y:.1}");
            }
            Some(old_y) => {
                let _ = write!(path, " L{x:.1},{old_y:.1} L{x:.1},{y:.1}");
            }
        }
        let _ = writeln!(marks, "<circle cx=\"{x:.1}\" cy=\"{y:.1}\" r=\"3\"/>");
        previous = Some(y);
    }
    if let Some(old_y) = previous {
        let _ = write!(path, " L{:.1},{old_y:.1}", SVG_WIDTH - SVG_RIGHT);
    }
    let body = format!(
        "<path d=\"{path}\" fill=\"none\" stroke=\"#3b82f6\" stroke-width=\"2\"/>\n<g fill=\"#3b82f6\">\n{marks}</g>\n\
         <g fill=\"currentColor\"><text x=\"{SVG_LEFT}\" y=\"{tick}\" text-anchor=\"middle\">0</text>\
         <text x=\"{right}\" y=\"{tick}\" text-anchor=\"middle\">{}</text></g>\n",
        last_generation.max(1),
        tick = SVG_HEIGHT - SVG_BOTTOM + 16.0,
        right = SVG_WIDTH - SVG_RIGHT,
    );
    Some(Float {
        kind: FloatKind::Figure,
        name: "improvement",
        description: "best correct score after each generation of the search",
        latex,
        markdown: format!(
            "![Improvement trace](figures/improvement.svg)\n\n**Figure {{N}}.** {caption}\n"
        ),
        svg: Some((
            "improvement.svg".to_string(),
            svg_frame(y_min, y_max, "Generation", "Best combined score", &body),
        )),
        home: "results",
    })
}

fn ablation_floats(data: &PaperData) -> Vec<Float> {
    let Some(summary) = &data.ablations else {
        return Vec::new();
    };
    let measured: Vec<_> = summary
        .variants
        .iter()
        .filter_map(|variant| variant.summary.as_ref().map(|stats| (variant, stats)))
        .collect();
    if measured.is_empty() {
        return Vec::new();
    }
    let rows: Vec<Vec<String>> = measured
        .iter()
        .map(|(variant, stats)| {
            let comparison = variant.comparison_to_control.as_ref();
            vec![
                variant.spec.variant_id.clone(),
                variant.spec.kind.clone(),
                stats.n.to_string(),
                format_metric(stats.mean),
                format_metric(stats.std),
                format_interval(stats.ci95_low, stats.ci95_high),
                comparison.map_or("n/a".to_string(), |c| format_metric(c.mean_diff)),
                comparison.map_or("n/a".to_string(), |c| format_p(c.p_value)),
            ]
        })
        .collect();
    let caption = format!(
        "Ablation study: combined score over {} replications per variant, with 95% intervals. The difference and Welch p-value are against the anchor variant, {}.",
        summary.num_replications, summary.anchor_variant_id
    );
    let mut floats = vec![table(
        "ablations",
        "every ablation variant with mean, standard deviation, 95% interval, difference to the control and p-value",
        "results",
        &caption,
        "llrrrrrr",
        &["Variant", "Kind", "n", "Mean", "Std", "95% interval", "Difference", "p"],
        rows,
    )];

    let drawn: Vec<(&str, f64, f64, f64)> = measured
        .iter()
        .filter_map(|(variant, stats)| {
            let half = (stats.ci95_high - stats.ci95_low) / 2.0;
            (stats.mean.is_finite() && half.is_finite()).then_some((
                variant.spec.variant_id.as_str(),
                stats.mean,
                half,
                stats.ci95_low,
            ))
        })
        .collect();
    if drawn.len() >= 2 {
        let mut figure_caption =
            "Mean combined score of each ablation variant with its 95% interval.".to_string();
        match measured.len() - drawn.len() {
            0 => {}
            1 => figure_caption.push_str(" 1 variant without a finite interval is not drawn."),
            left_out => {
                let _ = write!(
                    figure_caption,
                    " {left_out} variants without a finite interval are not drawn."
                );
            }
        }
        let coordinates: Vec<String> = drawn
            .iter()
            .enumerate()
            .map(|(index, (_, mean, half, _))| format!("({mean},{}) +- ({half},0)", index + 1))
            .collect();
        let ticks: Vec<String> = (1..=drawn.len()).map(|index| index.to_string()).collect();
        let labels: Vec<String> = drawn
            .iter()
            .map(|(id, ..)| format!("{{{}}}", escape_inline(id)))
            .collect();
        let latex = format!(
            "\\begin{{figure}}\n\\centering\n\\begin{{tikzpicture}}\n\\begin{{axis}}[width=0.8\\linewidth, height={:.1}cm, xlabel={{Combined score}}, \
             ytick={{{}}}, yticklabels={{{}}}, y dir=reverse, enlarge y limits={{abs=0.6}}]\n\
             \\addplot+[only marks, mark=*, error bars/.cd, x dir=both, x explicit] coordinates {{{}}};\n\\end{{axis}}\n\\end{{tikzpicture}}\n\
             \\caption{{{}}}\n\\label{{fig:ablations}}\n\\end{{figure}}\n",
            2.6 + 0.7 * drawn.len() as f64,
            ticks.join(","),
            labels.join(","),
            coordinates.join(" "),
            escape_inline(&figure_caption)
        );
        let rows: Vec<(String, f64, f64, f64)> = drawn
            .iter()
            .map(|(id, mean, half, low)| (id.to_string(), *mean, *low, low + 2.0 * half))
            .collect();
        floats.push(Float {
            kind: FloatKind::Figure,
            name: "ablations",
            description: "mean score of each ablation variant with its 95% interval",
            latex,
            markdown: format!(
                "![Ablation means](figures/ablations.svg)\n\n**Figure {{N}}.** {figure_caption}\n"
            ),
            svg: Some((
                "ablations.svg".to_string(),
                interval_svg(&rows, "Combined score"),
            )),
            home: "results",
        });
    }
    floats
}

/// Every table and figure this run's evidence supports.
pub fn available_floats(data: &PaperData) -> Vec<Float> {
    let mut floats = Vec::new();
    if !data.top_programs.is_empty() {
        let mut rows: Vec<Vec<String>> = data
            .top_programs
            .iter()
            .take(5)
            .enumerate()
            .map(|(rank, row)| {
                vec![
                    (rank + 1).to_string(),
                    row.name.clone(),
                    row.generation.to_string(),
                    format_metric(row.combined_score),
                ]
            })
            .collect();
        let shown = |seed: &crate::data::ProgramRow| {
            data.top_programs
                .iter()
                .take(5)
                .any(|row| row.program_id == seed.program_id)
        };
        if let Some(seed) = data
            .seed
            .as_ref()
            .filter(|seed| seed.correct && !shown(seed))
        {
            rows.push(vec![
                "seed".to_string(),
                seed.name.clone(),
                "0".to_string(),
                format_metric(seed.combined_score),
            ]);
        }
        floats.push(table(
            "results",
            "the highest-scoring correct programs of the search and the seed, with search-time scores",
            "results",
            "The highest-scoring correct programs found by the search, and the seed program. Scores are search-time scores.",
            "llrr",
            &["Rank", "Program", "Generation", "Combined score"],
            rows,
        ));
    }
    floats.extend(improvement_figure(data));
    floats.extend(ablation_floats(data));

    if let Some(manifest) = &data.final_evaluation {
        let correct = |episodes: &[genesis_scientist::artifacts::FinalEpisode]| {
            format!(
                "{}/{}",
                episodes.iter().filter(|episode| episode.correct).count(),
                episodes.len()
            )
        };
        let mut rows = Vec::new();
        for (label, stats, episodes) in [
            ("studied program", &manifest.candidate, &manifest.episodes),
            ("baseline", &manifest.baseline, &manifest.baseline_episodes),
        ] {
            if let Some(stats) = stats {
                rows.push(vec![
                    label.to_string(),
                    correct(episodes),
                    format_metric(stats.mean),
                    format_metric(stats.std),
                    format_interval(stats.ci95_low, stats.ci95_high),
                ]);
            }
        }
        if !rows.is_empty() {
            let caption = format!(
                "Sealed final evaluation on {} held-out seeds (evaluator: {}). Outcome: {}.",
                manifest.seeds.len(),
                manifest.evaluator,
                manifest.outcome
            );
            floats.push(table(
                "final",
                "the sealed final evaluation of the studied program and the baseline, with the qualification outcome",
                "results",
                &caption,
                "lrrrr",
                &["Program", "Correct episodes", "Mean", "Std", "95% interval"],
                rows,
            ));
        }
    }

    let totals = &data.totals;
    let mut rows = vec![
        vec![
            "Proposals attempted".to_string(),
            totals.attempts.to_string(),
        ],
        vec![
            "Programs evaluated (seed included)".to_string(),
            totals.evaluated_programs.to_string(),
        ],
        vec![
            "Programs judged correct".to_string(),
            totals.correct_programs.to_string(),
        ],
        vec![
            "Proposals with no evaluated program".to_string(),
            totals.failed_proposals.to_string(),
        ],
        vec!["Ideas generated".to_string(), totals.ideas.to_string()],
    ];
    if let Some(cost) = data
        .grounding_sources
        .get("result.total_cost_usd")
        .and_then(|source| source.value.as_f64())
    {
        rows.push(vec!["Model spend (USD)".to_string(), format_number(cost)]);
    }
    floats.push(table(
        "run_summary",
        "counts of the search: proposals, evaluated and correct programs, failed proposals, ideas, spend",
        "supplementary",
        "Summary of the search this paper reports on.",
        "lr",
        &["Quantity", "Value"],
        rows,
    ));
    floats
}

/// A rendered paper and what rendering found.
#[derive(Debug, Clone, PartialEq, Default)]
pub struct Assembled {
    pub tex: String,
    pub markdown: String,
    /// Citation keys used in the prose, in order of first use.
    pub cite_keys: Vec<String>,
    /// Placeholders that name nothing this run has.
    pub unresolved: Vec<String>,
    /// SVG files for `figures/`.
    pub figures: Vec<(String, String)>,
}

struct Layout<'a> {
    floats: BTreeMap<(FloatKind, &'a str), &'a Float>,
    numbers: BTreeMap<(FloatKind, &'a str), usize>,
    known_keys: HashSet<&'a str>,
}

impl Layout<'_> {
    fn latex_inlines(&self, items: &[Inline], unresolved: &mut Vec<String>) -> String {
        let mut out = String::new();
        for item in items {
            match item {
                Inline::Text(text) => out.push_str(&escape_latex(text)),
                Inline::Emph(text) => {
                    let _ = write!(out, "\\emph{{{}}}", escape_latex(text));
                }
                Inline::Strong(text) => {
                    let _ = write!(out, "\\textbf{{{}}}", escape_latex(text));
                }
                Inline::Code(text) => {
                    let _ = write!(out, "\\texttt{{{}}}", escape_latex(text));
                }
                Inline::Math(text) => {
                    let _ = write!(out, "${text}$");
                }
                Inline::Cite(keys) => {
                    let (known, unknown): (Vec<&String>, Vec<&String>) = keys
                        .iter()
                        .partition(|key| self.known_keys.contains(key.as_str()));
                    if !known.is_empty() {
                        let _ = write!(
                            out,
                            "\\citep{{{}}}",
                            known
                                .iter()
                                .map(|key| key.as_str())
                                .collect::<Vec<_>>()
                                .join(",")
                        );
                    }
                    for key in unknown {
                        let _ = write!(out, "\\textbf{{[{}?]}}", escape_latex(key));
                    }
                }
                Inline::Ref(kind, name) => match self.floats.get(&(*kind, name.as_str())) {
                    Some(float) => {
                        let prefix = if *kind == FloatKind::Table {
                            "tab"
                        } else {
                            "fig"
                        };
                        let _ = write!(out, "{}~\\ref{{{prefix}:{}}}", kind.word(), float.name);
                    }
                    None => {
                        let token = format!("{{{{REF:{}:{name}}}}}", kind.word().to_uppercase());
                        out.push_str(&escape_latex(&token));
                        unresolved.push(token);
                    }
                },
                Inline::Unresolved(token) => {
                    out.push_str(&escape_latex(token));
                    unresolved.push(token.clone());
                }
            }
        }
        out
    }

    fn markdown_inlines(&self, items: &[Inline]) -> String {
        let mut out = String::new();
        for item in items {
            match item {
                Inline::Text(text) => out.push_str(text),
                Inline::Emph(text) => {
                    let _ = write!(out, "*{text}*");
                }
                Inline::Strong(text) => {
                    let _ = write!(out, "**{text}**");
                }
                Inline::Code(text) => {
                    let _ = write!(out, "`{text}`");
                }
                Inline::Math(text) => {
                    let _ = write!(out, "${text}$");
                }
                Inline::Cite(keys) => {
                    let _ = write!(out, "[{}]", keys.join("; "));
                }
                Inline::Ref(kind, name) => match self.numbers.get(&(*kind, name.as_str())) {
                    Some(number) => {
                        let _ = write!(out, "{} {number}", kind.word());
                    }
                    None => {
                        let _ = write!(out, "{{{{REF:{}:{name}}}}}", kind.word().to_uppercase());
                    }
                },
                Inline::Unresolved(token) => out.push_str(token),
            }
        }
        out
    }
}

/// Render `draft` against `data`. Floats the draft did not place are added
/// to the end of their home section.
pub fn assemble(draft: &Draft, data: &PaperData, references: &[Reference]) -> Assembled {
    let floats = available_floats(data);
    let mut sections: Vec<(&'static str, &'static str, Vec<Block>)> = SECTIONS
        .iter()
        .map(|spec| (spec.key, spec.heading, parse_prose(draft.section(spec.key))))
        .collect();

    let mut unresolved = Vec::new();
    let mut placed: HashSet<(FloatKind, &str)> = HashSet::new();
    for (_, _, blocks) in &mut sections {
        blocks.retain(|block| match block {
            Block::Float(kind, name) => match floats
                .iter()
                .find(|float| float.kind == *kind && float.name == name)
            {
                Some(float) => placed.insert((float.kind, float.name)),
                None => {
                    unresolved.push(format!("{{{{{}:{name}}}}}", kind.word().to_uppercase()));
                    false
                }
            },
            _ => true,
        });
    }
    for float in &floats {
        if !placed.contains(&(float.kind, float.name)) {
            if let Some((_, _, blocks)) = sections.iter_mut().find(|(key, _, _)| *key == float.home)
            {
                blocks.push(Block::Float(float.kind, float.name.to_string()));
            }
        }
    }

    let mut numbers: BTreeMap<(FloatKind, &str), usize> = BTreeMap::new();
    let mut counters: BTreeMap<FloatKind, usize> = BTreeMap::new();
    let mut cite_keys: Vec<String> = Vec::new();
    for (_, _, blocks) in &sections {
        for block in blocks {
            if let Block::Float(kind, name) = block {
                if let Some(float) = floats
                    .iter()
                    .find(|float| float.kind == *kind && float.name == name)
                {
                    let counter = counters.entry(*kind).or_insert(0);
                    *counter += 1;
                    numbers.insert((float.kind, float.name), *counter);
                }
            }
        }
        for inline in crate::text::inlines(blocks) {
            if let Inline::Cite(keys) = inline {
                for key in keys {
                    if !cite_keys.contains(key) {
                        cite_keys.push(key.clone());
                    }
                }
            }
        }
    }

    let layout = Layout {
        floats: floats
            .iter()
            .map(|float| ((float.kind, float.name), float))
            .collect(),
        numbers,
        known_keys: references
            .iter()
            .map(|reference| reference.citation_key.as_str())
            .collect(),
    };
    let cited: Vec<&Reference> = cite_keys
        .iter()
        .filter_map(|key| {
            references
                .iter()
                .find(|reference| reference.citation_key == *key)
        })
        .collect();
    let title = if draft.title.trim().is_empty() {
        format!("Program search on {}", data.task_name)
    } else {
        draft.title.clone()
    };

    let mut tex = format!(
        "\\documentclass[11pt]{{article}}\n\\usepackage[utf8]{{inputenc}}\n\\usepackage[T1]{{fontenc}}\n\\IfFileExists{{lmodern.sty}}{{\\usepackage{{lmodern}}}}{{}}\n\\usepackage{{textcomp}}\n\
         \\usepackage[margin=1in]{{geometry}}\n\\usepackage{{amsmath,amssymb}}\n\\usepackage{{graphicx}}\n\\usepackage{{booktabs}}\n\
         \\usepackage[numbers]{{natbib}}\n\\usepackage{{tikz}}\n\\usepackage{{pgfplots}}\n\\pgfplotsset{{compat=1.15}}\n\\setlength{{\\belowcaptionskip}}{{6pt}}\n\
         \\IfFileExists{{float.sty}}{{\\usepackage{{float}}\\floatplacement{{table}}{{H}}\\floatplacement{{figure}}{{H}}}}{{}}\n\
         \\title{{{}}}\n\\author{{Genesis}}\n\\date{{}}\n\\begin{{document}}\n\\maketitle\n",
        escape_inline(&title)
    );
    let mut markdown = format!(
        "# {}\n\n*{GENERATED_BY}*\n\n",
        title.split_whitespace().collect::<Vec<_>>().join(" ")
    );

    for (key, heading, blocks) in &sections {
        match *key {
            "abstract" => tex.push_str("\\begin{abstract}\n"),
            "supplementary" => {
                if !cited.is_empty() {
                    tex.push_str("\\bibliographystyle{plainnat}\n\\bibliography{references}\n\n");
                }
                let _ = writeln!(tex, "\\clearpage\n\\appendix\n\\section{{{heading}}}");
            }
            _ => {
                let _ = writeln!(tex, "\\section{{{heading}}}");
            }
        }
        if *key == "supplementary" && !cited.is_empty() {
            markdown.push_str("## References\n\n");
            for reference in &cited {
                let authors = if reference.authors.is_empty() {
                    "Unknown authors".to_string()
                } else {
                    reference.authors.join(", ")
                };
                let year = reference
                    .year
                    .map_or("n.d.".to_string(), |year| year.to_string());
                let venue = if reference.venue.is_empty() {
                    String::new()
                } else {
                    format!(" {}.", reference.venue)
                };
                let _ = writeln!(
                    markdown,
                    "- **[{}]** {authors} ({year}). *{}*.{venue}",
                    reference.citation_key, reference.title
                );
            }
            markdown.push('\n');
        }
        let _ = writeln!(markdown, "## {heading}\n");

        for block in blocks {
            match block {
                Block::Heading(items) => {
                    let _ = writeln!(
                        tex,
                        "\\subsection{{{}}}",
                        layout.latex_inlines(items, &mut unresolved)
                    );
                    let _ = writeln!(markdown, "### {}\n", layout.markdown_inlines(items));
                }
                Block::Paragraph(items) => {
                    let _ = writeln!(tex, "{}\n", layout.latex_inlines(items, &mut unresolved));
                    let _ = writeln!(markdown, "{}\n", layout.markdown_inlines(items));
                }
                Block::List(rows) => {
                    tex.push_str("\\begin{itemize}\n");
                    for row in rows {
                        let _ =
                            writeln!(tex, "\\item {}", layout.latex_inlines(row, &mut unresolved));
                        let _ = writeln!(markdown, "- {}", layout.markdown_inlines(row));
                    }
                    tex.push_str("\\end{itemize}\n\n");
                    markdown.push('\n');
                }
                Block::Float(kind, name) => {
                    if let Some(float) = layout.floats.get(&(*kind, name.as_str())) {
                        let number = layout
                            .numbers
                            .get(&(float.kind, float.name))
                            .copied()
                            .unwrap_or(0);
                        tex.push_str(&float.latex);
                        tex.push('\n');
                        markdown.push_str(&float.markdown.replace("{N}", &number.to_string()));
                        markdown.push('\n');
                    }
                }
            }
        }
        match *key {
            "abstract" => {
                let _ = writeln!(
                    tex,
                    "\\end{{abstract}}\n\\begin{{center}}\\small\\emph{{{}}}\\end{{center}}\n",
                    escape_inline(GENERATED_BY)
                );
            }
            "limitations" if !data.limitations.is_empty() => {
                tex.push_str(
                    "The run itself records the following limitations.\n\\begin{itemize}\n",
                );
                markdown.push_str("The run itself records the following limitations.\n\n");
                for limitation in &data.limitations {
                    let _ = writeln!(tex, "\\item {}", escape_inline(limitation));
                    let _ = writeln!(markdown, "- {limitation}");
                }
                tex.push_str("\\end{itemize}\n\n");
                markdown.push('\n');
            }
            _ => {}
        }
    }
    tex.push_str("\\end{document}\n");

    unresolved.sort();
    unresolved.dedup();
    Assembled {
        tex,
        markdown,
        cite_keys,
        unresolved,
        figures: floats
            .iter()
            .filter_map(|float| float.svg.clone())
            .collect(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::data::{ProgramRow, Totals, TraceStep};

    fn data() -> PaperData {
        PaperData {
            task_name: "circle_packing".into(),
            top_programs: vec![ProgramRow {
                name: "restarts_50%".into(),
                generation: 4,
                combined_score: 2.635,
                correct: true,
                ..Default::default()
            }],
            seed: Some(ProgramRow {
                name: "initial_program".into(),
                combined_score: 1.9,
                correct: true,
                ..Default::default()
            }),
            improvement_trace: vec![
                TraceStep {
                    id: "result.improvement_001".into(),
                    generation: 0,
                    combined_score: 1.9,
                    name: "initial_program".into(),
                },
                TraceStep {
                    id: "result.improvement_002".into(),
                    generation: 4,
                    combined_score: 2.635,
                    name: "restarts".into(),
                },
            ],
            totals: Totals {
                attempts: 5,
                evaluated_programs: 5,
                correct_programs: 4,
                failed_proposals: 1,
                ideas: 0,
            },
            limitations: vec!["No ablation study is available for this run & nothing else.".into()],
            ..Default::default()
        }
    }

    fn draft(results: &str) -> Draft {
        let mut draft = Draft {
            title: "Restarts & packing".into(),
            ..Default::default()
        };
        for spec in SECTIONS {
            draft
                .sections
                .insert(spec.key.to_string(), format!("{} text.", spec.heading));
        }
        draft.sections.insert("results".into(), results.to_string());
        draft
    }

    #[test]
    fn numbers_are_shown_whole_or_to_four_decimals() {
        assert_eq!(format_number(26.0), "26");
        assert_eq!(format_number(2.63512), "2.6351");
        assert_eq!(format_number(-0.05), "-0.0500");
        assert_eq!(format_number(0.00012345), "1.23e-4");
        assert_eq!(format_number(f64::NAN), "n/a");
        assert_eq!(format_p(Some(0.0001)), "<0.001");
        assert_eq!(format_p(Some(0.0421)), "0.042");
        assert_eq!(
            (
                format_metric(6.0),
                format_metric(0.0),
                format_metric(0.00012345)
            ),
            ("6.0000".into(), "0.0000".into(), "1.23e-4".into())
        );
    }

    #[test]
    fn floats_are_placed_where_asked_and_appended_otherwise() {
        let references = vec![Reference {
            citation_key: "smith2020".into(),
            title: "Evolving code".into(),
            authors: vec!["A. Smith".into()],
            year: Some(2020),
            ..Default::default()
        }];
        let rendered = assemble(
            &draft("The trace in {{REF:FIGURE:improvement}} rises [@smith2020; @ghost1].\n\n{{FIGURE:improvement}}\n\n{{TABLE:ablations}}\n\nSee {{REF:TABLE:nothing}} and {{WHAT}}."),
            &data(),
            &references,
        );
        let tex = &rendered.tex;
        assert!(tex.contains("\\title{Restarts \\& packing}"));
        assert!(tex.contains(
            "Figure~\\ref{fig:improvement} rises \\citep{smith2020}\\textbf{[ghost1?]}."
        ));
        let figure = tex.find("\\label{fig:improvement}").unwrap();
        let table = tex.find("\\label{tab:results}").unwrap();
        assert!(
            figure < table,
            "the placed figure comes before the appended table"
        );
        assert!(tex.contains("restarts\\_50\\%"));
        assert!(tex.find("\\label{tab:run_summary}").unwrap() > tex.find("\\appendix").unwrap());
        assert!(tex.contains("\\bibliography{references}"));
        assert!(
            tex.contains("\\item No ablation study is available for this run \\& nothing else.")
        );
        assert_eq!(rendered.cite_keys, ["smith2020", "ghost1"]);
        assert_eq!(
            rendered.unresolved,
            ["{{REF:TABLE:nothing}}", "{{TABLE:ablations}}", "{{WHAT}}"]
        );
        assert_eq!(rendered.figures.len(), 1);
        assert!(
            rendered.figures[0].1.starts_with("<svg")
                && rendered.figures[0].1.contains("<path d=\"M")
        );

        let markdown = &rendered.markdown;
        assert!(markdown.starts_with("# Restarts & packing\n\n*Generated by Genesis"));
        assert!(markdown.contains("The trace in Figure 1 rises [smith2020; ghost1]."));
        assert!(markdown.contains("**Figure 1.** Best combined score"));
        assert!(markdown.contains("**Table 1.** The highest-scoring"));
        assert!(markdown.contains("**Table 2.** Summary of the search"));
        assert!(markdown.contains("| 1 | restarts_50% | 4 | 2.6350 |"));
        assert!(markdown.contains("- **[smith2020]** A. Smith (2020). *Evolving code*."));
    }

    #[test]
    fn without_citations_there_is_no_bibliography() {
        let rendered = assemble(&draft("Plain."), &data(), &[]);
        assert!(!rendered.tex.contains("\\bibliography"));
        assert!(!rendered.markdown.contains("## References"));
        assert!(rendered.unresolved.is_empty() && rendered.cite_keys.is_empty());
    }
}
